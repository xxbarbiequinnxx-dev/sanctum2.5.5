function mulberry32(seed: number) {
  return () => {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function yearOrder(length: number, year: number) {
  const order = Array.from({ length }, (_, i) => i);
  const rand = mulberry32(year * 9973 + length);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j]!, order[i]!];
  }
  return order;
}

export function dayKey(date = new Date()) {
  return date.toISOString().slice(0, 10);
}

export function dayOfYearUtc(date = new Date()) {
  const year = date.getUTCFullYear();
  const start = Date.UTC(year, 0, 0);
  return Math.floor((date.getTime() - start) / 86400000);
}

export function todaysCard(date = new Date()) {
  const order = yearOrder(DAILY_QUESTIONS.length, date.getUTCFullYear());
  const index = order[dayOfYearUtc(date) % order.length]!;
  return {
    prompt: DAILY_QUESTIONS[index]!,
    number: index + 1,
    total: DAILY_QUESTIONS.length,
    date: dayKey(date),
  };
}

export function todaysQuestion(date = new Date()) {
  return todaysCard(date).prompt;
}
