export type IdeaGroup = {
  slug: string;
  label: string;
  starts: string[];
  ends: string[];
};

function weave(starts: string[], ends: string[]) {
  const out: string[] = [];
  const seen = new Set<string>();
  for (let i = 0; i < starts.length; i += 1) {
    for (let j = 0; j < ends.length; j += 1) {
      const text = `${starts[i]} ${ends[j]}`.replace(/\s+/g, " ").trim();
      if (seen.has(text)) continue;
      seen.add(text);
      out.push(text);
    }
  }
  return out;
}

function pack(slug: string, label: string, starts: string[], ends: string[]): IdeaGroup {
  if (starts.length * ends.length < 500) {
    throw new Error(`${slug} needs at least 500 combinations (has ${starts.length * ends.length})`);
  }
  return { slug, label, starts: starts.slice(0, 25), ends: ends.slice(0, 20) };
}

